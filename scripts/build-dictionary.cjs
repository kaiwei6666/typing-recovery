// Usage: node scripts/build-dictionary.cjs path/to/BPMFBase.txt
// Source is pinned and verified; see third_party/mcbopomofo/README.md.
const { readFileSync, writeFileSync } = require("node:fs");
const { resolve } = require("node:path");
const { createHash } = require("node:crypto");

const source = readFileSync(process.argv[2]);
const sha256 = createHash("sha256").update(source).digest("hex");
if (sha256 !== "46e64a53dc9c6baa2cbe6e0b1af572f8ef6aafb50597178b5fd53df804316ce7") {
  throw new Error("Unexpected dictionary source. Review provenance before updating the pinned hash.");
}
const readings = Object.create(null);
for (const line of source.toString("utf8").split(/\r?\n/)) {
  const [character, reading, , , encoding] = line.trim().split(/\s+/);
  // Use the upstream Big5 Han subset; omit phonetic symbols and UTF-8-only variants.
  if (encoding !== "big5" || !/^\p{Script=Han}$/u.test(character)) continue;
  if (!/^[ㄅ-ㄩ]+[ˊˇˋ˙]?$/.test(reading)) throw new Error(`Unexpected reading: ${reading}`);
  const candidates = readings[reading] ??= [];
  if (!candidates.includes(character)) candidates.push(character);
}
const sorted = Object.fromEntries(Object.entries(readings).sort(([a], [b]) => a < b ? -1 : 1));
const body = Object.entries(sorted).map(([reading, candidates]) =>
  `  ${JSON.stringify(reading)}: ${JSON.stringify(candidates.join(""))}`).join(",\n");
const output = `// Generated by scripts/build-dictionary.cjs; do not edit by hand.\n` +
  `// McBopomofo f5ba010ce8795d283ee336ca7d16380f200bd2ec, MIT.\n` +
  `// Copyright (c) 2011-2026 Mengjuei Hsieh et al.\n` +
  `// Full license and provenance: third_party/mcbopomofo/.\n` +
  `globalThis.ZHUYIN_DICTIONARY = Object.freeze({\n${body}\n});\n`;
writeFileSync(resolve(__dirname, "../src/core/dictionary.js"), output);
console.log(`${Object.keys(sorted).length} readings, ${Object.values(sorted).reduce((n, chars) => n + chars.length, 0)} candidates`);
